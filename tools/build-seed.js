#!/usr/bin/env node
/**
 * build-seed.js – liest bela.config.json und erzeugt js/config/seed.js.
 *
 * Warum nicht die JSON-Datei direkt laden? Browser dürfen auf file:// keine
 * Dateien per fetch lesen. Ein kleines JS-Setup ist der einzige Weg, der ohne
 * Server und ohne Build-Schritt funktioniert. Die JSON-Datei bleibt die
 * bearbeitbare Quelle.
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { normalizeSeed } = require('../js/core/progress.js');

const ROOT = path.join(__dirname, '..');
const CONFIG = path.join(ROOT, 'bela.config.json');
const TARGET = path.join(ROOT, 'js', 'config', 'seed.js');

function buildSeed() {
  if (!fs.existsSync(CONFIG)) {
    throw new Error('bela.config.json not found. Run ./setup.sh first.');
  }

  let raw;
  try {
    raw = JSON.parse(fs.readFileSync(CONFIG, 'utf8'));
  } catch (error) {
    throw new Error('bela.config.json is not valid JSON: ' + error.message);
  }

  if (raw.version !== 1) {
    throw new Error('bela.config.json has version ' + raw.version + ', expected 1.');
  }

  const seed = normalizeSeed(raw);
  const body = seed
    ? 'window.BELA_SEED = ' + JSON.stringify(seed, null, 2) + ';\n'
    : 'window.BELA_SEED = null;\n';

  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, '/* Generated by tools/build-seed.js from bela.config.json. Do not edit by hand. */\n' + body);

  return { seed, target: TARGET };
}

if (require.main === module) {
  try {
    const result = buildSeed();
    const count = result.seed ? result.seed.profiles.length : 0;
    console.log('Wrote ' + path.relative(ROOT, result.target) + ' with ' + count + ' profile(s).');
    if (!count) {
      console.log('No profiles in bela.config.json — the app will create one unnamed profile.');
    }
  } catch (error) {
    console.error('Seed error: ' + error.message);
    process.exit(1);
  }
}

module.exports = { buildSeed };
